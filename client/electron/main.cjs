// Extract the protocol handling logic
function handleProtocolUrl(url) {
  console.log("Received URL:", url);

  const win = BrowserWindow.getAllWindows()[0];
  if (!win) {
    console.log("No window found");
    return;
  }

  try {
    const myURL = new URL(url);
    const code = myURL.searchParams.get("code");
    const error = myURL.searchParams.get("error");

    if (error) {
      console.error("OAuth error:", error);
      win.webContents.send("auth-error", error);
      return;
    }

    if (code) {
      console.log("Received auth code:", code);

      // Exchange the code for an access token
      exchangeCodeForToken(code)
        .then((tokenResponse) => {
          console.log("Token exchange successful");
          win.webContents.send("auth-success", tokenResponse.access_token);
        })
        .catch((tokenError) => {
          console.error("Token exchange failed:", tokenError);
          win.webContents.send("auth-error", "Token exchange failed");
        });

      // Bring the window to focus
      win.show();
      win.focus();
    }
  } catch (parseError) {
    console.error("Error parsing URL:", parseError);
    win.webContents.send("auth-error", "Invalid callback URL");
  }
}
function createWindow() {
  const win = new BrowserWindow({
    width: 1200,
    height: 800,
    icon: path.join(__dirname, "../public/assets", "rookieclip3.ico"),
    webPreferences: {
      nodeIntegration: false,
      contextIsolation: true,
      enableRemoteModule: true,
      webSecurity: false,
      allowRunningInsecureContent: true,
      experimentalFeatures: true,
      preload: path.join(__dirname, "preload.js"),
      hardwareAcceleration: true,
      // Optimize for animations
      backgroundThrottling: false,
    },
  });
  win.removeMenu();
  win.webContents.on("before-input-event", (event, input) => {
    const isRefresh =
      (input.control || input.meta) && input.key.toLowerCase() === "r";

    if (isRefresh) {
      win.reload();
      event.preventDefault();
    }
  });

  isDev
    ? win.loadURL("http://localhost:5173")
    : win.loadURL("https://rookieclip.com");

  if (isDev) win.webContents.openDevTools();

  return win;
}

