let isRecordingClicks = false;
let intervalId = null;
let cursorDataObj = [];
let cursorData = [];
let _recordingStartTime = null;
let recordingStartTimestamp = null;

ipcMain.on("toggle-recording", (event, recordingStartTime) => {
  console.log(
    "Toggle recording called, current state:",
    isRecordingClicks,
    recordingStartTime
  );

  if (isRecordingClicks) {
    // Stop recording
    console.log("Stopping recording...");
    const sessionData = stopRecording();
    if (sessionData) {
      event.reply("recording-stopped", sessionData);
    } else {
      event.reply("recording-cancelled");
    }
  } else {
    // Start recording
    console.log("Starting recording...");
    startRecording(recordingStartTime);
    event.reply("recording-started");
  }
});

ipcMain.on("force-stop-recording", (event) => {
  console.log("Force stop recording called");
  if (isRecordingClicks) {
    const sessionData = stopRecording();
    event.reply("recording-force-stopped", sessionData || cursorDataObj);
  } else {
    event.reply("recording-force-stopped", cursorDataObj);
  }
});

function startRecording(recordingStartTime) {
  console.log("Starting recording with start time:", recordingStartTime);

  _recordingStartTime = recordingStartTime;
  recordingStartTimestamp = Date.now(); // Add this line
  isRecordingClicks = true;
  cursorData = []; // Reset cursor data for new recording

  // Immediately capture first cursor position
  const { x, y } = screen.getCursorScreenPoint();
  const timestamp = (Date.now() - _recordingStartTime) / 1000; // Convert to seconds with decimals
  cursorData.push({ x, y, timestamp });
  console.log("Initial cursor position captured:", { x, y, timestamp });

  // Change interval to 100ms for smooth tracking
  intervalId = setInterval(() => {
    if (!isRecordingClicks) {
      clearInterval(intervalId);
      return;
    }

    const { x, y } = screen.getCursorScreenPoint();
    const timestamp = (Date.now() - _recordingStartTime) / 1000; // Convert to seconds with decimals
    console.log("Cursor position captured:", { x, y, timestamp });

    cursorData.push({ x, y, timestamp });
  }, 500);
}

function stopRecording() {
  if (!isRecordingClicks) {
    console.log("Not recording, nothing to stop");
    return null;
  }

  const actualRecordingDuration = Date.now() - recordingStartTimestamp;
  isRecordingClicks = false;

  if (intervalId) {
    clearInterval(intervalId);
    intervalId = null;
  }

  // Check for minimum recording duration and minimum data points
  if (cursorData.length === 0) {
    console.log("No cursor data collected, skipping session");
    cursorData = [];
    return null;
  }

  if (actualRecordingDuration < 200) {
    console.log("Recording too short (< 200ms), skipping session");
    cursorData = [];
    return null;
  }

  // Create session with correct structure for MediaPlayer
  const recordingSession = {
    startTime: cursorData[0].timestamp,
    endTime: cursorData[cursorData.length - 1].timestamp,
    cursorData: [...cursorData],
    createdAt: new Date().toISOString(),
    zoomLevel: 1.5,
    isAutoGenerated: true,
  };
  const relativeCursorData = recordingSession.cursorData.map((data) => {
    return {
      ...data,
      timestamp: data.timestamp - recordingSession.startTime, // Make timestamps relative to start time
    };
  });
  recordingSession.cursorData = relativeCursorData;
  cursorDataObj.push(recordingSession);
  console.log("Recording session added. Total sessions:", cursorDataObj.length);
  console.log("Session data:", recordingSession);

  // Reset for next recording
  cursorData = [];
  recordingStartTimestamp = null;

  return recordingSession;
}
